package com.calmify.backend.pdf;

import com.calmify.backend.dto.ReportPdfDto;
import com.calmify.backend.entity.MoodEntry;
import com.lowagie.text.Document;
import com.lowagie.text.DocumentException;
import com.lowagie.text.Font;
import com.lowagie.text.PageSize;
import com.lowagie.text.Paragraph;
import com.lowagie.text.pdf.PdfPTable;
import com.lowagie.text.pdf.PdfWriter;
import org.springframework.stereotype.Component;

import java.io.ByteArrayOutputStream;
import java.time.LocalDate;

@Component
public class PdfGenerator {

    public byte[] generateReport(ReportPdfDto report) {

        try {

            ByteArrayOutputStream outputStream = new ByteArrayOutputStream();

            Document document = new Document(PageSize.A4);
            PdfWriter.getInstance(document, outputStream);

            document.open();

            Font titleFont = new Font(Font.HELVETICA, 20, Font.BOLD);

            Paragraph title =
                    new Paragraph("Calmify Mental Health Report", titleFont);

            title.setAlignment(Paragraph.ALIGN_CENTER);

            document.add(title);

            document.add(new Paragraph(" "));
            document.add(new Paragraph("Generated Date : " + LocalDate.now()));

            document.add(new Paragraph(" "));
            document.add(new Paragraph("Name : " + report.getName()));
            document.add(new Paragraph("Email : " + report.getEmail()));

            document.add(new Paragraph(" "));
            document.add(new Paragraph("----------- SUMMARY -----------"));

            document.add(new Paragraph("Total Entries : " + report.getTotalEntries()));
            document.add(new Paragraph("Current Mood : " + report.getCurrentMood()));
            document.add(new Paragraph("Most Frequent Mood : " + report.getMostFrequentMood()));

            document.add(new Paragraph(" "));
            document.add(new Paragraph("----------- MOOD HISTORY -----------"));

            PdfPTable table = new PdfPTable(3);

            table.setWidthPercentage(100);

            table.addCell("Date");
            table.addCell("Mood");
            table.addCell("Note");

            for (MoodEntry mood : report.getMoodEntries()) {

                table.addCell(mood.getCreatedAt().toLocalDate().toString());
                table.addCell(mood.getMood());
                table.addCell(mood.getNote());

            }

            document.add(table);

            document.add(new Paragraph(" "));
            document.add(new Paragraph("Generated by Calmify"));

            document.close();

            return outputStream.toByteArray();

        } catch (DocumentException e) {

            throw new RuntimeException(e);

        }

    }

}